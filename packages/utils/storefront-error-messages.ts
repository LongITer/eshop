// Translate fixed server templates only; keep product titles and specification values intact.
export function dynamicStorefrontError(text: string, language: 'vi' | 'en'): string | undefined {
  if (language !== 'vi') return undefined;
  const patterns: Array<[RegExp, (...values: string[]) => string]> = [
    [/^Choose an available variant for (.+)$/, name => `Hãy chọn biến thể còn hàng cho ${name}`],
    [/^(?:Choose|Select) options for (.+)$/, name => `Hãy chọn tùy chọn cho ${name}`],
    [/^Select a variant for (.+)$/, name => `Hãy chọn biến thể cho ${name}`],
    [/^(.+) is out of stock\.?$/, name => `${name} đã hết hàng.`],
    [/^CPU \/ motherboard socket mismatch: (.+) \/ (.+)\.$/, (cpu, board) => `Socket CPU / bo mạch chủ không tương thích: ${cpu} / ${board}.`],
    [/^RAM \/ motherboard memory type mismatch: (.+) \/ (.+)\.$/, (ram, board) => `Loại bộ nhớ RAM / bo mạch chủ không tương thích: ${ram} / ${board}.`],
    [/^GPU recommends at least (\d+(?:\.\d+)?) W; selected PSU is (\d+(?:\.\d+)?) W\.$/, (needed, chosen) => `GPU đề xuất nguồn tối thiểu ${needed} W; nguồn đã chọn là ${chosen} W.`],
  ];
  for (const [pattern, render] of patterns) { const match = pattern.exec(text); if (match) return render(...match.slice(1)); }
  return undefined;
}
